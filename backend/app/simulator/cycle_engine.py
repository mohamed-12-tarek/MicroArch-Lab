"""Cycle-by-cycle execution engine for the MicroArch Lab pipeline."""

from typing import Any, Optional

from app.core.errors import SimulationError
from app.core.hazard_unit import detect_hazard, resolve_forwarding
from .pipeline_state import PipelineState, StageSlot


class CycleEngine:
    """
    Executes one pipeline cycle at a time.

    Pipeline stages:
        IF -> ID -> EX -> MEM -> WB

    Uses Processor for ALU, registers, memory and control signals.
    Uses the M5 Hazard Unit for stall detection and forwarding.
    """

    def __init__(self, processor: Any, instructions: list):
        self.processor = processor
        self.instructions = list(instructions)
        self._current_forwards: list[dict[str, Any]] = []

    # =========================================================
    # General Helpers
    # =========================================================

    @staticmethod
    def _instruction_id(instruction: Any) -> Optional[int]:
        return None if instruction is None else getattr(instruction, "instruction_id", None)

    @staticmethod
    def _destination(instruction: Any) -> Optional[str]:
        if instruction is None:
            return None
        destination_method = getattr(instruction, "destination_register", None)
        return destination_method() if callable(destination_method) else getattr(instruction, "rd", None)

    @staticmethod
    def _slot_instruction(slot: Optional[StageSlot]) -> Any:
        return None if slot is None else slot.instruction

    @staticmethod
    def _is_empty_slot(slot: Optional[StageSlot]) -> bool:
        return slot is None or slot.is_empty

    @staticmethod
    def _copy_slot(slot: Optional[StageSlot]) -> Optional[StageSlot]:
        return slot.copy() if slot is not None else None

    @staticmethod
    def _is_load(instruction: Any) -> bool:
        return instruction is not None and instruction.opcode.upper() == "LW"

    @staticmethod
    def _set_operand(slot: StageSlot, register: str, value: int) -> bool:
        """Store value in every source operand of the slot that uses register.

        Returns True if at least one operand (rs1 and/or rs2) matched.
        """
        matched = False
        for name in ("rs1", "rs2"):
            operand = getattr(slot.instruction, name)
            if operand is not None and operand.upper() == register.upper():
                setattr(slot, f"{name}_value", value)
                matched = True
        return matched

    def _raise_for_instruction(self, message: str, instruction: Any) -> None:
        error = SimulationError(message, instruction=instruction)
        error.line_number = getattr(instruction, "line_number", None)
        raise error

    def _run_component(self, operation, instruction: Any) -> Any:
        """Convert component exceptions into instruction-aware simulation errors."""
        try:
            return operation()
        except SimulationError as exc:
            line_number = getattr(instruction, "line_number", None)
            if exc.line is None:
                exc.line = line_number or None
            if not hasattr(exc, "line_number") or exc.line_number is None:
                exc.line_number = line_number
            raise
        except Exception as exc:
            error = SimulationError(str(exc), instruction=instruction)
            error.line_number = getattr(instruction, "line_number", None)
            raise error from exc

    def _decode(self, instruction: Any) -> Any:
        """Get the control signals generated by the Processor's ControlUnit."""
        return self._run_component(lambda: self.processor.decode(instruction), instruction)

    # =========================================================
    # WB Stage
    # =========================================================

    def _write_back(self, slot: Optional[StageSlot]) -> None:
        if self._is_empty_slot(slot):
            return

        instruction = slot.instruction
        if not self._decode(instruction).reg_write:
            return

        destination = self._destination(instruction)
        if destination is None:
            self._raise_for_instruction("Register-writing instruction has no destination register.", instruction)

        if destination.upper() == "R0":
            return

        if slot.write_value is None:
            self._raise_for_instruction("Missing write-back value.", instruction)

        self._run_component(lambda: self.processor.write_reg(destination, slot.write_value), instruction)

    # =========================================================
    # ID Stage
    # =========================================================

    def _read_registers(self, slot: Optional[StageSlot]) -> None:
        if self._is_empty_slot(slot):
            return

        instruction = slot.instruction

        # Use the Instruction model to identify the source registers.
        for register in instruction.source_registers():
            value = self._run_component(lambda reg=register: self.processor.read_reg(reg), instruction)
            self._set_operand(slot, register, value)

    # =========================================================
    # Forwarding
    # =========================================================

    def _resolve_forwarding(
        self,
        ex_slot: Optional[StageSlot],
        mem_slot: Optional[StageSlot],
        wb_slot: Optional[StageSlot],
    ) -> dict:
        if self._is_empty_slot(ex_slot):
            return {}

        return self._run_component(
            lambda: resolve_forwarding(
                self._slot_instruction(ex_slot),
                self._slot_instruction(mem_slot),
                self._slot_instruction(wb_slot),
            ),
            ex_slot.instruction,
        )

    def _apply_forwarding(
        self,
        ex_slot: Optional[StageSlot],
        mem_slot: Optional[StageSlot],
        wb_slot: Optional[StageSlot],
        forwarding_map: dict,
    ) -> None:
        if self._is_empty_slot(ex_slot):
            return

        instruction = ex_slot.instruction

        # The Hazard Unit uses a set internally, so sort the results
        # to guarantee deterministic forwarding-event order.
        for register, source_info in sorted(forwarding_map.items(), key=lambda item: item[0].upper()):
            if not isinstance(source_info, dict):
                self._raise_for_instruction(f"Invalid forwarding information for {register}.", instruction)

            source_stage = source_info.get("from_stage")
            if source_stage == "MEM":
                source_slot = mem_slot
            elif source_stage == "WB":
                source_slot = wb_slot
            else:
                self._raise_for_instruction(f"Unsupported forwarding stage: {source_stage}.", instruction)

            if self._is_empty_slot(source_slot):
                self._raise_for_instruction(
                    f"Forwarding source {register} is missing from {source_stage}.", instruction
                )

            source_instruction = source_slot.instruction
            actual_source_id = self._instruction_id(source_instruction)
            expected_source_id = source_info.get("from_instruction")

            # Verify that the Hazard Unit selected the instruction
            # that is actually present in the requested pipeline stage.
            if expected_source_id != actual_source_id:
                self._raise_for_instruction(
                    f"Forwarding source mismatch for {register}: expected instruction {expected_source_id}, "
                    f"found instruction {actual_source_id} in {source_stage}.",
                    instruction,
                )

            actual_destination = self._destination(source_instruction)
            if actual_destination is None or actual_destination.upper() != register.upper():
                self._raise_for_instruction(
                    f"Forwarding source instruction {actual_source_id} does not write to {register}.",
                    instruction,
                )

            # MEM forwarding is allowed only for non-load instructions.
            if source_stage == "MEM" and self._is_load(source_instruction):
                self._raise_for_instruction(
                    "Invalid forwarding state: LW in MEM cannot forward its value to EX.", instruction
                )

            forwarded_value = source_slot.alu_result if source_stage == "MEM" else source_slot.write_value
            if forwarded_value is None:
                self._raise_for_instruction(f"Forwarding value for {register} is not available.", instruction)

            # Update whichever source operand uses this register.
            if not self._set_operand(ex_slot, register, forwarded_value):
                self._raise_for_instruction(
                    f"Instruction does not use forwarding register {register}.", instruction
                )

            self._current_forwards.append(
                {
                    "register": register,
                    "from_stage": source_stage,
                    "from_instruction": actual_source_id,
                    "to_instruction": self._instruction_id(instruction),
                }
            )

    # =========================================================
    # EX Stage
    # =========================================================

    def _execute(self, slot: Optional[StageSlot]) -> None:
        if self._is_empty_slot(slot):
            return

        instruction = slot.instruction
        control = self._decode(instruction)

        # NOP has no ALU operation.
        if control.alu_op is None:
            return

        if slot.rs1_value is None:
            self._raise_for_instruction("Missing first source operand in EX stage.", instruction)

        # ControlUnit decides whether the second ALU operand
        # comes from a register or from the immediate.
        if control.alu_src:
            if instruction.immediate is None:
                self._raise_for_instruction("Missing immediate operand in EX stage.", instruction)
            operand_b = instruction.immediate
        else:
            if slot.rs2_value is None:
                self._raise_for_instruction("Missing second source operand in EX stage.", instruction)
            operand_b = slot.rs2_value

        result = self._run_component(
            lambda: self.processor.alu_execute(control.alu_op, slot.rs1_value, operand_b),
            instruction,
        )
        slot.alu_result = result

        # ALU instructions write the ALU result.
        # LW gets its final write_value later in MEM.
        if control.reg_write and not control.mem_to_reg:
            slot.write_value = result

    # =========================================================
    # MEM Stage
    # =========================================================

    def _memory_access(self, slot: Optional[StageSlot]) -> None:
        if self._is_empty_slot(slot):
            return

        instruction = slot.instruction
        control = self._decode(instruction)

        if control.mem_read:
            if slot.alu_result is None:
                self._raise_for_instruction("Missing memory address for load instruction.", instruction)

            slot.write_value = self._run_component(lambda: self.processor.load(slot.alu_result), instruction)

        elif control.mem_write:
            if slot.alu_result is None or slot.rs2_value is None:
                self._raise_for_instruction("Missing address or source value for store instruction.", instruction)

            self._run_component(lambda: self.processor.store(slot.alu_result, slot.rs2_value), instruction)

    # =========================================================
    # Hazard Detection
    # =========================================================

    def _detect_stall(self, state: PipelineState) -> tuple[bool, Optional[str]]:
        id_instruction = self._slot_instruction(state.ID)
        ex_instruction = self._slot_instruction(state.EX)

        if id_instruction is None or ex_instruction is None:
            return False, None

        result = self._run_component(lambda: detect_hazard(id_instruction, ex_instruction), id_instruction)

        if result is None:
            return False, None

        # M5 returns (should_stall, message).
        if isinstance(result, tuple):
            if len(result) != 2:
                self._raise_for_instruction("Invalid result returned by hazard detection.", id_instruction)
            should_stall, reason = result
            return bool(should_stall), reason

        # Keep compatibility with a boolean-only implementation.
        if isinstance(result, bool):
            return result, None

        self._raise_for_instruction("Invalid result returned by hazard detection.", id_instruction)

    # =========================================================
    # One Pipeline Cycle
    # =========================================================

    def step(self, state: PipelineState) -> PipelineState:
        """
        Execute exactly one pipeline cycle.

        The input state is never modified.
        A new PipelineState is returned.
        """
        if not isinstance(state, PipelineState):
            raise TypeError("step() expects a PipelineState object.")

        # 1. Detect hazards using the CURRENT state.
        has_stall, stall_reason = self._detect_stall(state)

        new_state = PipelineState(
            pc=state.pc,
            stall=has_stall,
            stall_reason=str(stall_reason) if has_stall and stall_reason else None,
            forwards=[],
        )

        # 2. Move instructions between stages.
        if has_stall:
            # Freeze IF and ID, and insert a bubble into EX.
            new_state.IF = self._copy_slot(state.IF)
            new_state.ID = self._copy_slot(state.ID)
            new_state.EX = None
        else:
            # Fetch the next instruction (IF stays empty once the program is fetched).
            if state.pc < len(self.instructions):
                new_state.IF = StageSlot(instruction=self.instructions[state.pc])
                new_state.pc = state.pc + 1

            new_state.ID = self._copy_slot(state.IF)
            new_state.EX = self._copy_slot(state.ID)

        # Older instructions always move forward, stalled or not.
        new_state.MEM = self._copy_slot(state.EX)
        new_state.WB = self._copy_slot(state.MEM)

        # 3. Execute stage operations.
        self._current_forwards = []

        # WB writes the instruction that is in WB during THIS cycle (new_state.WB),
        # before ID reads the register file. Writing state.WB instead (the previous
        # cycle's WB) delays every result by one cycle, so a consumer 3 instructions
        # behind its producer would read a stale value: it is too late for ID to see
        # the write and too old for forwarding (which only covers MEM and WB).
        self._write_back(new_state.WB)

        # ID reads register values after WB has completed.
        self._read_registers(new_state.ID)

        # Resolve and apply forwarding for EX.
        forwarding_map = self._resolve_forwarding(new_state.EX, new_state.MEM, new_state.WB)
        self._apply_forwarding(new_state.EX, new_state.MEM, new_state.WB, forwarding_map)

        # Execute the ALU operation.
        self._execute(new_state.EX)

        # Perform memory access.
        self._memory_access(new_state.MEM)

        new_state.forwards = list(self._current_forwards)
        return new_state

    # =========================================================
    # Pipeline Completion
    # =========================================================

    def is_finished(self, state: PipelineState) -> bool:
        """
        Check whether all instructions have completed
        and all pipeline stages are empty.
        """
        return state.pc >= len(self.instructions) and all(
            self._is_empty_slot(slot) for slot in (state.IF, state.ID, state.EX, state.MEM, state.WB)
        )